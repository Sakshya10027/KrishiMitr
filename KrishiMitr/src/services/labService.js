/**
 * Filter laboratories across all states and districts of India
 * @param {Object} options
 * @param {string} options.state - Indian State or UT name
 * @param {string} options.district - District name
 * @param {string} options.labType - Filter by type (Static, KVK, Mobile Van, etc.)
 * @param {string} options.searchTerm - Free text search query
 * @returns {Array} List of matching laboratories
 */
export function getLabsByLocation({ state = '', district = '', labType = '', searchTerm = '' } = {}) {
  let results = [];

  const cleanState = (state || '').trim();
  const cleanDistrict = (district || '').trim();
  const term = (searchTerm || '').trim().toLowerCase();

  // If a specific state and district are provided
  if (cleanState && cleanDistrict) {
    // 1. Get curated labs that match this state & district
    const curatedMatches = CURATED_LABS.filter(
      lab => lab.state.toLowerCase() === cleanState.toLowerCase() &&
             lab.district.toLowerCase() === cleanDistrict.toLowerCase()
    );

    // 2. Supplement with official generated accredited labs if curated count is small
    const generated = generateDistrictLabs(cleanState, cleanDistrict);
    
    // Combine, avoiding duplicates by name similarity
    const existingNames = new Set(curatedMatches.map(c => c.name.toLowerCase()));
    const supplemental = generated.filter(g => !existingNames.has(g.name.toLowerCase()));
    
    results = [...curatedMatches, ...supplemental];
  } 
  // If only State is selected (all districts of that state)
  else if (cleanState) {
    const curatedForState = CURATED_LABS.filter(
      lab => lab.state.toLowerCase() === cleanState.toLowerCase()
    );

    const availableDistricts = STATES_AND_DISTRICTS[cleanState] || [];
    const generatedForState = [];

    // Provide at least 1-2 prominent labs for the first 5-8 districts in that state
    for (const dist of availableDistricts.slice(0, 8)) {
      const alreadyHas = curatedForState.some(c => c.district.toLowerCase() === dist.toLowerCase());
      if (!alreadyHas) {
        const distLabs = generateDistrictLabs(cleanState, dist);
        generatedForState.push(distLabs[0]); // Add primary DSTL
      }
    }

    results = [...curatedForState, ...generatedForState];
  }
  // If no state selected, return national curated showcase
  else {
    results = [...CURATED_LABS];
  }

  // Filter by lab type if selected
  if (labType && labType !== 'All') {
    results = results.filter(lab => {
      if (labType === 'Static' || labType === 'District HQ') {
        return lab.type.includes('Static (District HQ)') || lab.type.includes('State Level');
      }
      if (labType === 'KVK') {
        return lab.type.includes('KVK');
      }
      if (labType === 'Mobile') {
        return lab.type.includes('Mobile');
      }
      if (labType === 'University') {
        return lab.type.includes('University') || lab.type.includes('Research');
      }
      return lab.type.toLowerCase().includes(labType.toLowerCase());
    });
  }

  // Filter by keyword search if provided
  if (term) {
    results = results.filter(lab => {
      const matchName = lab.name.toLowerCase().includes(term);
      const matchDist = lab.district.toLowerCase().includes(term);
      const matchState = lab.state.toLowerCase().includes(term);
      const matchAddr = lab.address.toLowerCase().includes(term);
      const matchInCharge = lab.inCharge.toLowerCase().includes(term);
      const matchCaps = (lab.testCapabilities || []).some(c => c.toLowerCase().includes(term));
      return matchName || matchDist || matchState || matchAddr || matchInCharge || matchCaps;
    });
  }

  return results;
}
